/**
 * Shared KPI scoring engine.
 *
 * Brief §6.3 asks for this to be built once and reused by all four modules,
 * since every category follows the same
 * target -> achievement -> rating -> weighted-score pattern.
 */

export type Rating = 1 | 2 | 3 | 4

/** Standard rating guide from the brief. Evaluated top-down, first match wins. */
export const RATING_BANDS = [
  { min: 100, rating: 4 as Rating, label: "100% & above" },
  { min: 90, rating: 3 as Rating, label: "90% – 99%" },
  { min: 75, rating: 2 as Rating, label: "75% – 89%" },
  { min: 0, rating: 1 as Rating, label: "Below 75%" },
] as const

/**
 * "higher" — actual/target (more is better: bookings, AOV, CSAT…)
 * "lower"  — target/actual (less is better: design freeze cycle time)
 *
 * The brief states Achievement % = Actual / Target globally, but cycle time is
 * a lower-is-better metric: a designer who freezes a design in 6 days against a
 * 9-day target would score a 1 under the literal formula. Flagged for Richard.
 */
export type Direction = "higher" | "lower"

export type Unit = "currency" | "percent" | "days" | "count" | "score"

export interface SubKpi {
  id: string
  label: string
  /** Fraction of the parent category, 0–1. Siblings sum to 1. */
  weight: number
  direction: Direction
  unit: Unit
  /** Shown as tooltip help on the scorecard. */
  definition: string
}

export interface Category {
  id: string
  label: string
  short: string
  /** Fraction of the final score, 0–1. All categories sum to 1. */
  weight: number
  /** Categorical palette slot, 1-indexed. Fixed per category — never by rank. */
  slot: 1 | 2 | 3 | 4 | 5
  subKpis: SubKpi[]
}

