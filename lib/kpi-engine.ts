export const SUB_KPIS = KPI_TREE.flatMap((c) =>
  c.subKpis.map((s) => ({ ...s, categoryId: c.id, categoryLabel: c.label })),
)

export const SUB_KPI_IDS = SUB_KPIS.map((s) => s.id)
export type SubKpiId = (typeof SUB_KPI_IDS)[number]

export function subKpiById(id: string) {
  return SUB_KPIS.find((s) => s.id === id)
}

/**
 * Achievement % for one sub-KPI. Returns null when it cannot be computed —
 * callers render that as an em dash rather than a misleading 0%.
 */
export function achievementPct(
  actual: number | null | undefined,
  target: number | null | undefined,
  direction: Direction = "higher",
): number | null {
  if (actual == null || target == null) return null
  if (!Number.isFinite(actual) || !Number.isFinite(target)) return null
  if (target <= 0) return null
  if (direction === "lower") {
    if (actual <= 0) return null
    return (target / actual) * 100
  }
  return (actual / target) * 100
}

/** Rating 1–4 from achievement %, per the standard rating guide. */
export function ratingFor(pct: number | null): Rating | null {
  if (pct == null || !Number.isFinite(pct)) return null
  for (const band of RATING_BANDS) {
    if (pct >= band.min) return band.rating
  }
  return 1
}

/**
 * Category weighted score = Σ (sub-KPI rating × sub-KPI weight).
 * Weights of scoreable sub-KPIs are renormalised so an unmeasured sub-KPI
 * doesn't silently drag the category toward zero.
 */
export function categoryScore(
  subs: { rating: Rating | null; weight: number }[],
): number | null {
  const scoreable = subs.filter((s) => s.rating != null)
  if (scoreable.length === 0) return null
  const totalWeight = scoreable.reduce((sum, s) => sum + s.weight, 0)
  if (totalWeight <= 0) return null
  return scoreable.reduce((sum, s) => sum + s.rating! * s.weight, 0) / totalWeight
}

/** Final KPI score = Σ (category score × category weight). Same renormalisation. */
export function finalScore(
  cats: { score: number | null; weight: number }[],
): number | null {
  const scoreable = cats.filter((c) => c.score != null)
  if (scoreable.length === 0) return null
  const totalWeight = scoreable.reduce((sum, c) => sum + c.weight, 0)
  if (totalWeight <= 0) return null
  return scoreable.reduce((sum, c) => sum + c.score! * c.weight, 0) / totalWeight
}

/** Where a 1–4 score sits as a percentage of the 4.0 ceiling. */
export function scoreToPct(score: number | null): number | null {
  return score == null ? null : (score / 4) * 100
}

export const SCORE_BANDS = [
  { min: 3.5, label: "Outstanding", rating: 4 as Rating },
  { min: 3.0, label: "Exceeds", rating: 3 as Rating },
  { min: 2.0, label: "Meets", rating: 2 as Rating },
  { min: 0, label: "Needs Improvement", rating: 1 as Rating },
] as const

export function scoreBand(score: number | null) {
  if (score == null) return null
  return SCORE_BANDS.find((b) => score >= b.min) ?? SCORE_BANDS[SCORE_BANDS.length - 1]
}

// ---------------------------------------------------------------------------
// Composition: one designer's full scorecard from raw target/actual pairs.
// ---------------------------------------------------------------------------

export interface MetricInput {
  target: number | null
  actual: number | null
}

export type MetricInputs = Record<string, MetricInput>

export interface ScoredSubKpi extends SubKpi {
  target: number | null
  actual: number | null
  achievement: number | null
  rating: Rating | null
  /** rating × weight — this row's contribution to the category score. */
  weighted: number | null
}

export interface ScoredCategory extends Omit<Category, "subKpis"> {
  subKpis: ScoredSubKpi[]
  score: number | null
  /** score × category weight — contribution to the final score. */
  weighted: number | null
}

export interface Scorecard {
  categories: ScoredCategory[]
  final: number | null
  band: (typeof SCORE_BANDS)[number] | null
}

export function buildScorecard(inputs: MetricInputs): Scorecard {
  const categories: ScoredCategory[] = KPI_TREE.map((cat) => {
    const subKpis: ScoredSubKpi[] = cat.subKpis.map((sub) => {
      const { target = null, actual = null } = inputs[sub.id] ?? {}
      const achievement = achievementPct(actual, target, sub.direction)
      const rating = ratingFor(achievement)
      return {
        ...sub,
        target,
        actual,
        achievement,
        rating,
        weighted: rating == null ? null : rating * sub.weight,
      }
    })
    const score = categoryScore(subKpis)
    return { ...cat, subKpis, score, weighted: score == null ? null : score * cat.weight }
  })

  const final = finalScore(categories)
  return { categories, final, band: scoreBand(final) }
}

/** Average a set of scorecards for an EC or manager rollup. */
export function averageScorecards(cards: Scorecard[]): Scorecard {
  const categories: ScoredCategory[] = KPI_TREE.map((cat, ci) => {
    const subKpis: ScoredSubKpi[] = cat.subKpis.map((sub, si) => {
      const rows = cards.map((c) => c.categories[ci].subKpis[si])
      const target = sumOrNull(rows.map((r) => r.target))
      const actual = sumOrNull(rows.map((r) => r.actual))
      // Rate/score units average across people; volume units sum.
      const aggregate = sub.unit === "percent" || sub.unit === "score" || sub.unit === "days"
      const t = aggregate ? meanOrNull(rows.map((r) => r.target)) : target
      const a = aggregate ? meanOrNull(rows.map((r) => r.actual)) : actual
      const achievement = achievementPct(a, t, sub.direction)
      const rating = ratingFor(achievement)
      return {
        ...sub,
        target: t,
        actual: a,
        achievement,
        rating,
        weighted: rating == null ? null : rating * sub.weight,
      }
    })
    const score = categoryScore(subKpis)
    return { ...cat, subKpis, score, weighted: score == null ? null : score * cat.weight }
  })
  const final = finalScore(categories)
  return { categories, final, band: scoreBand(final) }
}

function sumOrNull(values: (number | null)[]): number | null {
  const nums = values.filter((v): v is number => v != null)
  return nums.length ? nums.reduce((a, b) => a + b, 0) : null
}

function meanOrNull(values: (number | null)[]): number | null {
  const nums = values.filter((v): v is number => v != null)
  return nums.length ? nums.reduce((a, b) => a + b, 0) / nums.length : null
}
